// Bahasa yang tidak dikenal atau kunci yang kosong jatuh ke bahasa Inggris; `labels` menimpa per kunci.
export function resolveText(lang = 'id', labels = {}) {
  const base = { ...LOCALES.en, ...LOCALES[lang] }
  // String & daftar (mis. shortcutList) diganti utuh; tombol digabung per properti.
  return Object.fromEntries(Object.entries(base).map(([k, v]) => [k, typeof v === 'string' || Array.isArray(v) ? labels[k] ?? v : mergeButton(v, labels[k])]))
}

// Jika pengguna hanya mengganti `label`, ikon SVG bawaan dibuang agar label itu yang tampil.
function mergeButton(base, o = {}) {
  const merged = { ...base, ...o }
  if ('label' in o && !('html' in o)) delete merged.html
  return merged
}
